%section 1
v_duration = 2;
v_start = -1;
v_end = 1;
f_sample = 50;
n_samples = v_duration * f_sample;
t_step = 1/f_sample;
t_vector = v_start : t_step : v_end - t_step;
f_signal = 5; 
s_x1 = cos(2*pi*f_signal*t_vector);
figure;
stem(t_vector, s_x1, 'Color', [0.85 0.33 0.10], 'Marker', 'o', 'MarkerFaceColor', [0.85 0.33 0.10]); 
xlabel('Time (s)', 'FontSize', 12);
ylabel('Amplitude', 'FontSize', 12);
title('x_1(t) Time Domain', 'FontSize', 14, 'Interpreter', 'latex');
xlim([v_start, v_end - t_step]);
ylim([-1.1, 1.1]);
grid on;
set(gca, 'GridLineStyle', ':');
y_fft = fftshift(fft(s_x1));
N_fft = length(s_x1);
res_freq = f_sample/N_fft; 
f_vector = -f_sample/2 : res_freq : f_sample/2 - res_freq;
m_spectral = abs(y_fft) / N_fft; 
figure;
plot(f_vector, m_spectral, 'LineWidth', 2, 'Color', [0 0.4470 0.7410]);
xlabel('Frequency (Hz)', 'FontSize', 12);
ylabel('Magnitude', 'FontSize', 12); 
title('coeffients', 'FontSize', 14);
xlim([-2*f_signal - res_freq, 2*f_signal + res_freq]);
ylim([0, 0.6]); 
grid on;
set(gca, 'GridLineStyle', '--');
%section 2
v_duration = 1;
v_start = 0;
v_end = 1;
f_sample = 100;
n_samples = v_duration * f_sample;
t_step = 1/f_sample;
t_vector = v_start : t_step : v_end - t_step;
f_signal = 15; 
p_initial = pi/4;
s_x2 = cos(2*pi*f_signal*t_vector + p_initial);
figure;
stem(t_vector, s_x2, 'Color', [0.85 0.33 0.10], 'Marker', 'o', 'MarkerFaceColor', [0.85 0.33 0.10]); 
xlabel('Time (s)', 'FontSize', 12);
ylabel('Amplitude', 'FontSize', 12);
title('Signal x_2(t) in Time Domain', 'FontSize', 14, 'Interpreter', 'latex');
xlim([v_start, v_end - t_step]);
ylim([-1.1, 1.1]);
grid on;
set(gca, 'GridLineStyle', ':');
y_fft = fftshift(fft(s_x2));
N_fft = length(s_x2);
res_freq = f_sample/N_fft; 
f_vector = -f_sample/2 : res_freq : f_sample/2 - res_freq;
m_normalized = abs(y_fft) / max(abs(y_fft));
figure;
plot(f_vector, m_normalized, 'LineWidth', 2, 'Color', [0 0.4470 0.7410]);
xlabel('Frequency (Hz)', 'FontSize', 12);
ylabel('Magnitude', 'FontSize', 12);
title('Magnitude Spectrum of x_2(t)', 'FontSize', 14);
xlim([-2*f_signal - res_freq, 2*f_signal + res_freq]);
ylim([0, 1.1]);
grid on;
set(gca, 'GridLineStyle', '--');
t_zero = 1e-6;
y_fft_clean = y_fft;
y_fft_clean(abs(y_fft_clean) < t_zero) = 0;
p_angle = angle(y_fft_clean);
figure;
plot(f_vector, p_angle / pi, 'LineWidth', 2, 'Color', [0.4660 0.6740 0.1880]); 
xlabel('Frequency (Hz)', 'FontSize', 12);
ylabel('Phase/\pi', 'FontSize', 12);
title('Phase Spectrum of x_2(t)', 'FontSize', 14);
xlim([-2*f_signal - res_freq, 2*f_signal + res_freq]); 
ylim([-0.3, 0.3]);
yticks([-0.25, 0, 0.25]); 
yticklabels({'-1/4', '0', '1/4'});
grid on;
set(gca, 'GridLineStyle', '-');
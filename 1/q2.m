aTrue = -1.8;
bTrue  = 3.2;
t = 0:0.001:1;
x = cos(2 * pi * t);
yTrue = aTrue * x + bTrue;
noise = 0.05;
yNoisy = yTrue + noise * randn(size(yTrue));
[aEstimated, bEstimated] = p2_4(x, yNoisy);
fprintf('True a: %.4f | Estimated a: %.4f\n', aTrue, aEstimated);
fprintf('True b : %.4f | Estimated b : %.4f\n', bTrue, bEstimated);
figure;
plot(x, yNoisy, '.');
xlabel("x"), ylabel("y"), title("Test-Fitted");
hold on;
plot(x, aEstimated * x + bEstimated, 'r', 'LineWidth', 2);
